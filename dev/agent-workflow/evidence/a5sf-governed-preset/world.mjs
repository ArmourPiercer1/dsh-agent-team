#!/usr/bin/env node
/**
 * a5sf-governed-preset-world.mjs — build ONE DEV-LIVE world home that opts the
 * shipped Team row into the governed Member preset (2026-11-11 owner ruling).
 *
 * The world is a real DSH_HOME under `tests/homes/` (workspace-writable) whose
 * `profiles/web/cordis.patch.yml` overrides the shipped `dsh-agent-team` row:
 *   - `blueprintSource` becomes a schemaVersion 4 design carrying a
 *     `memberIoCeilings` family (the ONLY permission statement),
 *   - `memberPresetId: a5sf-governed-member` (the shipped preset row),
 *   - `a5sfGovernedRealm: true` (the neutral enablement key),
 * and registers the governed preset row itself.
 *
 * The row `name` is the package specifier `dsh-agent-team/host`, resolved
 * through a symlink the caller places in the pinned host tree (see the README's
 * reproduction section); nothing here rewrites upstream.
 *
 * Usage: node dev/agent-workflow/evidence/a5sf-governed-preset/world.mjs <home>
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, '..', '..', '..', '..')
const require_ = createRequire(join(REPO_ROOT, 'package.json'))
const YAML = require_('yaml')

const home = process.argv[2]
if (!home) {
  console.error('usage: world.mjs <home>')
  process.exit(2)
}
const homePath = resolve(home)
const workspace = join(homePath, 'workspace')
mkdirSync(join(homePath, 'profiles', 'web'), { recursive: true })
mkdirSync(workspace, { recursive: true })
mkdirSync(join(homePath, 'workspace-write-only'), { recursive: true })
writeFileSync(join(workspace, 'in-lane.txt'), 'in lane\n', 'utf8')
writeFileSync(join(homePath, 'workspace-write-only', 'secret.txt'), 'A5SF_GOVERNED_SECRET_BYTES\n', 'utf8')

/** The v4 design: the ceiling family IS the permission statement. */
const blueprint = {
  schemaVersion: 4,
  blueprintId: 'governed-preset-team',
  revision: '1',
  leader: { templateId: 'leader', persona: 'You lead this team.' },
  members: [{ templateId: 'worker', displayName: 'Worker A', persona: 'You are a worker on this team.' }],
  requirements: [],
  memberEnvelopes: [{ templateId: 'worker', envelope: { allow: [ 'send-message', 'report-progress' ], deny: [] } }],
  policyStates: [{ id: 'default', description: 'Default state.' }],
  permissionMutationEnvelope: { rules: [] },
  teamHardEnvelope: { rules: [] },
  metadata: {},
  memberIoCeilings: [{
    templateId: 'worker',
    io: {
      read: { mode: 'restricted', allow: [workspace], ask: [], deny: [] },
      write: { mode: 'restricted', allow: [workspace], ask: [], deny: [] },
      network: { mode: 'allow' },
    },
  }],
}
const blueprintSource = `---\n${JSON.stringify(blueprint, null, 2)}\n---\n`

const shipped = YAML.parse(require_('fs').readFileSync(join(REPO_ROOT, 'cordis.patch.yml'), 'utf8').replace(/!!js /g, ''))
const rows = []
const visit = (list) => { for (const row of list ?? []) { if (Array.isArray(row?.insert)) { visit(row.insert); continue } rows.push(row) } }
visit(shipped)
const hostRow = rows.find((row) => row?.name === 'dsh-agent-team/host')
const presetRow = rows.find((row) => row?.config?.id === 'a5sf-governed-member')
if (hostRow === undefined || presetRow === undefined) {
  console.error('the shipped layer did not carry the host row or the governed preset row')
  process.exit(1)
}

const config = {
  ...hostRow.config,
  blueprintSource,
  defaultWorkspace: workspace,
  // THE OPT-IN, EXPLICIT ON BOTH KEYS (the ruling's "selectable only by an
  // explicit memberPresetId"): the preset name and the neutral realm marker.
  memberPresetId: 'a5sf-governed-member',
  a5sfGovernedRealm: true,
  // The evidence sink the guarded shell writes its read decisions to.
  a5sfEvidencePath: join(homePath, 'a5sf-governed-consult.jsonl'),
}

const patch = {
  insert: [
    // DEV-LIVE only: an ABSOLUTE module path (the canary-row precedent) so the
    // loader import cannot depend on host-tree resolution. The SHIPPED row uses
    // the package specifier `dsh-agent-team/host`.
    { id: 'dsh-agent-team', name: process.env.A5SF_HOST_ENTRY ?? join(REPO_ROOT, 'packages', 'runtime', 'dist', 'packages', 'runtime', 'src', 'plugin', 'host.js'), config },
    { id: 'preset-a5sf-governed-member', name: '@deepseek-ai/dsh-agent-preset', config: presetRow.config },
  ],
}
const header = [
  'DEV-LIVE world for the GOVERNED-PRESET ruling (2026-11-11).',
  'Generated by dev/agent-workflow/evidence/a5sf-governed-preset/world.mjs.',
  'The Team row is overridden to opt into the governed Member preset: v4 blueprint + memberIoCeilings,',
  'memberPresetId a5sf-governed-member, a5sfGovernedRealm true. Nothing else is changed.',
]
writeFileSync(join(homePath, 'profiles', 'web', 'cordis.patch.yml'), `${header.map((line) => `# ${line}`).join('\n')}\n- insert:\n${YAML.stringify(patch.insert, { lineWidth: 0 }).split('\n').map((line) => (line === '' ? '' : `    ${line}`)).join('\n')}\n`, 'utf8')
console.log(JSON.stringify({ home: homePath, workspace, patch: join(homePath, 'profiles', 'web', 'cordis.patch.yml') }))
