#!/usr/bin/env python3
"""A4-PR2 lane A mutation-proof generator.

Flips PRODUCTION code (never a test), runs the named lane-A test file, records
whether the suite noticed, and restores the file with `git checkout --`.
Run from the worktree root:  python3 dev/.../generate-lane-a.py
"""
import subprocess
AC='packages/runtime/governance/authority-ceiling.ts'
RA='packages/runtime/governance/runtime-authority.ts'
OUT='dev/agent-workflow/evidence/a4-pr2/mutation-proofs/lane-a-mutation-proofs.txt'
lines=[f"# A4-PR2 lane A mutation proofs - generated by generate-lane-a.py in this directory.",
       "# Every flip is in PRODUCTION source; no test file is written by this script.",
       f"# HEAD {subprocess.run(['git','rev-parse','--short','HEAD'],capture_output=True,text=True).stdout.strip()}.",""]
def run(label, path, old, new, test):
    src=open(path).read()
    if src.count(old)!=1:
        lines.append(f"## {label}\n- ANCHOR ERROR count={src.count(old)} - proof not run\n")
        open(OUT,'w').write('\n'.join(lines)); subprocess.run(['git','checkout','--',path]); return False
    open(path,'w').write(src.replace(old,new))
    p=subprocess.run(['npx','vitest','run',test],capture_output=True,text=True)
    tail=[l.strip() for l in (p.stdout+p.stderr).split('\n') if l.strip().startswith('Tests ')]
    failed=p.returncode!=0
    lines.append(f"## {label}\n- file: {path}\n- flip: {old.strip()[:110]!r} -> {new.strip()[:110]!r}\n- test: {test}\n- result: {tail[0] if tail else 'no summary'}\n- verdict: {'RED (the suite noticed)' if failed else 'GREEN (NOTHING NOTICED)'}\n- caught: {failed}\n")
    open(OUT,'w').write('\n'.join(lines))
    subprocess.run(['git','checkout','--',path])
    return failed
T1='packages/runtime/test/a4p2-ceiling-reachability.test.ts'
T2='packages/runtime/test/a4p2-authority-ceiling.test.ts'
T3='packages/runtime/test/a4p1-authority-envelope.test.ts'
r=[]
r.append(run('M1 expansionCeiling read an ABSENT bound slot as "skip it" (the X7-R5 relaxation)',AC,"      ceilings.push(CEILING_NO_AUTHORITY)\n      continue","      continue",T1))
r.append(run('M2 expansionCeiling computed on the APPROVAL lookup (the fused-lookup hole)',AC,"effectiveAuthorityCeiling(resolved.document, scope.operationClass, scope.matcher, subtreeContains)","narrowingForApproval(resolved.document, scope, subtreeContains)",T1))
r.append(run('M3 mayReview allowed a same-level reviewer (>= instead of >)',AC,"return reviewerRank > beneficiaryRank && reviewerRank >= requiredRank","return reviewerRank >= beneficiaryRank && reviewerRank >= requiredRank",T2))
r.append(run('M4 authorityRank answered a default rank instead of refusing',AC,"  if (typeof position !== 'string' || !Object.hasOwn(AUTHORITY_RANK, position)) {\n    throw outsideLadder('authorityRank', position)\n  }","  if (typeof position !== 'string' || !Object.hasOwn(AUTHORITY_RANK, position)) return -1",T2))
r.append(run('M5 the rank map dropped the human-admin row',AC,"  'human-admin': 3,\n} as const","} as const",T2))
r.append(run('M6 the rank map swapped leader and human-user',AC,"  leader: 1,\n  'human-user': 2,","  leader: 2,\n  'human-user': 1,",T2))
r.append(run('M7 the Leader row dropped its mutation-envelope binding',AC,"  leader: Object.freeze(['teamHardEnvelope', 'permissionMutationEnvelope'] as const),","  leader: Object.freeze(['teamHardEnvelope'] as const),",T1))
r.append(run('M8 an unknown position bound NOTHING instead of refusing (invariant #16)',AC,"  if (typeof reviewer !== 'string' || !Object.hasOwn(BOUND_AUTHORITY_DOCUMENTS, reviewer)) {","  if (false) {",T3))
r.append(run('M9 the evaluator stopped re-checking required inputs at the boundary',RA,"    if (value === undefined || value === null) {","    if (false) {",T2))
r.append(run("M10 the evaluator's `direct` arm was made unreachable",RA,"outcome: mayReview(initiatorAuthority, beneficiaryAuthority, required) ? 'direct' : 'approval-required',","outcome: 'approval-required',",T2))
r.append(run('M11 mayReview gave requiredAuthority a default (X7-R2)',AC,"  requiredAuthority: ProposalAuthorityPosition,\n): boolean {","  requiredAuthority: ProposalAuthorityPosition = 'member',\n): boolean {",T2))
r.append(run('M12 the ladder alias was re-spelled as a local union (X7-R3)',RA,"\nexport type RuntimeAuthority = ProposalAuthorityPosition","\nexport type RuntimeAuthority = 'member' | 'leader' | 'human-user' | 'human-admin'",T2))
r.append(run('M13 the evaluator rose past an UNDETERMINED ceiling instead of stopping',RA,"    if (ceiling.status === 'undetermined') {","    if (false) {",T2))
lines.append(f"\n# SUMMARY: {sum(r)}/{len(r)} mutations were caught by the suite\n")
open(OUT,'w').write('\n'.join(lines))
print(f"{sum(r)}/{len(r)} caught")
