#!/usr/bin/env python3
"""A4-PR2 lane B mutation-proof generator (production flips only; see generate-lane-a.py)."""
import os, shutil, subprocess
PM='packages/runtime/governance/permission-mutation.ts'
OUT='dev/agent-workflow/evidence/a4-pr2/mutation-proofs/lane-b-mutation-proofs.txt'
T='packages/runtime/test/a3p3-revoke-reveal-semantics.test.ts'
lines=[f"# A4-PR2 lane B mutation proofs - generated by generate-lane-b.py.",
       f"# HEAD {subprocess.run(['git','rev-parse','--short','HEAD'],capture_output=True,text=True).stdout.strip()}.",
       "# The A3 suite (28 legs) is the behaviour net; the 5 lane-B legs are the extraction net.",""]
PRISTINE='/tmp/lane-b-pristine.ts'
def run(label, old, new, test=T):
    # NOTE (learned the hard way in this PR): restore from a saved COPY, never
    # `git checkout --`. The first run of this script blew away an uncommitted
    # refactor that way, turning four real proofs into anchor misses.
    src=open(PM).read()
    if not os.path.exists(PRISTINE): shutil.copyfile(PM, PRISTINE)
    if src.count(old)!=1:
        lines.append(f"## {label}\n- ANCHOR ERROR count={src.count(old)} - proof not run\n"); open(OUT,'w').write('\n'.join(lines)); shutil.copyfile(PRISTINE, PM); return False
    open(PM,'w').write(src.replace(old,new))
    p=subprocess.run(['npx','vitest','run',test],capture_output=True,text=True)
    tail=[l.strip() for l in (p.stdout+p.stderr).split('\n') if l.strip().startswith('Tests ')]
    failed=p.returncode!=0
    lines.append(f"## {label}\n- flip: {old.strip()[:90]!r} -> {new.strip()[:90]!r}\n- test: {test}\n- result: {tail[0] if tail else 'no summary'}\n- verdict: {'RED (the suite noticed)' if failed else 'GREEN (NOTHING NOTICED)'}\n- caught: {failed}\n")
    open(OUT,'w').write('\n'.join(lines)); shutil.copyfile(PRISTINE, PM); return failed
r=[]
r.append(run('N1 the classifier stopped reporting rise regions (the v3 ceiling gate would see nothing to gate)',
  "        rising.push(riseRegion)",
  "        // rising.push(riseRegion) — the ceiling gate is now blind"))
r.append(run('N2 the refusal order was inverted (EXPANSION reported before CONTEXT)',
  "  const firstUndeterminable = classification.undeterminable[0]",
  "  const firstUnmet0 = classification.unmet[0]\n  if (firstUnmet0 !== undefined) {\n    refuse(PERMISSION_MUTATION_ERROR_CODES.EXPANSION_OUTSIDE_ENVELOPE, 'expansion-region-uncovered', 'inverted', firstUnmet0.detail)\n  }\n  const firstUndeterminable = classification.undeterminable[0]"))
r.append(run('N3 unknown envelope coverage was relabeled covered (the X5 deny-masquerade class)',
  "    return coverageUnknown ? 'coverage-unknown' : 'unmet'", "    return 'covered'"))
r.append(run('N4 the coverage judge stopped respecting the risen effect (ladder-strict dropped)',
  "      if (PERMISSION_EFFECT_PRECEDENCE[region.risenEffect] > PERMISSION_EFFECT_PRECEDENCE[rule.maximumEffect]) continue",
  "      if (false) continue"))
r.append(run('N5 the coverage judge ran even when the caller asked for no judgement',
  "        if (coverage !== undefined) {", "        if (true) {"))
r.append(run('N6 the pre-classification subtree gate was moved AFTER classification',
  "  if (subtreeContains === undefined) {\n    const relevantClasses", "  if (false) {\n    const relevantClasses"))
lines.append(f"\n# SUMMARY: {sum(r)}/{len(r)} mutations were caught by the suite\n")
open(OUT,'w').write('\n'.join(lines)); print(f"{sum(r)}/{len(r)} caught")
