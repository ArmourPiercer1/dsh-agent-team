#!/usr/bin/env node
/**
 * gen-family-index — regenerate `packages/tools/families/index.mjs` (the
 * static import index the governed plane loads) from the REVIEWED manifest
 * `packages/tools/families/manifest.json` (u7-w0b S3).
 *
 * The manifest is the reviewed list: one entry per descriptor module, each
 * with the module's sha256. This script never adds a module to the list and
 * never rewrites a digest on its own — a new or changed family module is a
 * reviewed manifest edit. It only (a) derives the index from the manifest,
 * and (b) with `--check`, fails if the index on disk is not the derived one,
 * if a module under `packages/tools/families/` is not in the manifest, or if
 * a listed digest does not match the module bytes.
 *
 *   node scripts/gen-family-index.mjs            write index.mjs
 *   node scripts/gen-family-index.mjs --check    verify, exit 1 on drift
 *   node scripts/gen-family-index.mjs --digest   print each module's sha256
 */
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = join(root, 'packages/tools/families')
const manifestPath = join(dir, 'manifest.json')
const indexPath = join(dir, 'index.mjs')
const sha256 = (p) => createHash('sha256').update(readFileSync(p)).digest('hex')

export function familyModulesOnDisk() {
  return readdirSync(dir).filter((f) => f.endsWith('.mjs') && f !== 'index.mjs').sort()
}

export function renderFamilyIndex(manifest) {
  const lines = [
    '// GENERATED by scripts/gen-family-index.mjs from manifest.json — do not edit.',
    '// The reviewed family set: one static import per manifest entry, in manifest',
    '// order. The plane verifies every module against its reviewed digest before',
    '// any family mounts (runtime/src/plugin/live/family-assembly.mjs).',
  ]
  manifest.families.forEach((e, i) => {
    lines.push(`import { familyAssembly as f${String(i)} } from './${e.module}'`)
  })
  lines.push('')
  lines.push("import { dirname, join } from 'node:path'")
  lines.push("import { fileURLToPath } from 'node:url'")
  lines.push('')
  lines.push("export const FAMILY_MANIFEST_PATH = join(dirname(fileURLToPath(import.meta.url)), 'manifest.json')")
  lines.push('export const FAMILY_INDEX = Object.freeze([')
  manifest.families.forEach((e, i) => {
    lines.push(`  Object.freeze({ module: '${e.module}', familyAssembly: f${String(i)} }),`)
  })
  lines.push('])')
  return `${lines.join('\n')}\n`
}

function main(argv) {
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'))
  if (argv.includes('--digest')) {
    for (const f of familyModulesOnDisk()) console.log(`${sha256(join(dir, f))}  ${f}`)
    return 0
  }
  const rendered = renderFamilyIndex(manifest)
  if (!argv.includes('--check')) {
    writeFileSync(indexPath, rendered)
    console.log(`gen-family-index: wrote ${String(manifest.families.length)} entr(ies)`)
    return 0
  }
  const problems = []
  const listed = manifest.families.map((e) => e.module)
  for (const f of familyModulesOnDisk()) {
    if (!listed.includes(f)) problems.push(`unreviewed module on disk: ${f}`)
  }
  for (const e of manifest.families) {
    let actual
    try {
      actual = sha256(join(dir, e.module))
    } catch {
      problems.push(`listed module missing: ${e.module}`)
      continue
    }
    if (actual !== e.sha256) problems.push(`digest drift: ${e.module} is ${actual}, manifest says ${e.sha256}`)
  }
  let onDisk = ''
  try {
    onDisk = readFileSync(indexPath, 'utf8')
  } catch {
    problems.push('index.mjs missing')
  }
  if (onDisk !== rendered) problems.push('index.mjs is not the index derived from manifest.json (run without --check)')
  for (const p of problems) console.error(`gen-family-index: ${p}`)
  if (problems.length === 0) console.log(`gen-family-index: OK (${String(listed.length)} reviewed famil(ies))`)
  return problems.length === 0 ? 0 : 1
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)))
