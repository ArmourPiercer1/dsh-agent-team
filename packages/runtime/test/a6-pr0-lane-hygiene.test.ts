/**
 * Alpha.6 PR0 (Lane 2) — lane hygiene: what this lane is allowed to touch, and
 * who is allowed to consume it.
 *
 * Three laws, each the kind that is invisible while it holds:
 *
 *  1. DORMANT IS DECLARED, NOT ASSUMED. PR0 ships the delegation law with NO
 *     production consumer: no reviewer decision is wired to `allow` until the
 *     named Center-Interface PR (execution-plan PR-I1) passes its safety gate
 *     (gate G-5). A lane that is dark is safe only while it stays dark, so the
 *     import set is measured from disk on every run rather than asserted from
 *     a comment.
 *  2. THE LANE NEVER DEPENDS ON THE PROTECTED CENTER. Every decision entrance
 *     this lane can serve lives inside the ARC-A digest-pinned set
 *     (`control/**`); a reverse import would put a new lane in the compile
 *     graph of the kernel and make the next Center-Interface PR a merge of two
 *     directions. So: the lane's own imports of protected prefixes are zero.
 *  3. THE LANE IS IN THE COMPILE FACE. A lane nothing typechecks is a lane
 *     whose law drifts silently — the recurring review condition "the lane
 *     never entered a repo-wide tsc". Both tsconfigs must name it.
 */

import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, statSync, symlinkSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'vitest'

const RUNTIME_ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const LANE_DIR = join(RUNTIME_ROOT, 'review-mandate')
const PACKAGES_ROOT = join(RUNTIME_ROOT, '..')

/** Production source files that may import the lane. Empty until PR-I1 wires
 *  it — and PR-I1 must arrive WITH its Center-Interface ledger override, its
 *  own tests and this list updated in the same change, never as a stray edit. */
/**
 * Production consumers of the delegation vocabulary. One entry, added by Alpha.6 PR2′ (#507) — the
 * first PR after PR0 that is allowed to exist, and the mechanism this list was built for: a consumer is
 * named in the PR that adds it, and everything unnamed stays a failure.
 *
 * `review-assignment/router.ts` imports PR0 for exactly one reason, and it is the reason PR0 exists:
 * the router calls `evaluateReviewAdmission` (plus `isParsedReviewPlan` and `DELEGABLE_REVIEW_RUNG`) so
 * that the router can never be wider than the admission gate. A router that re-implemented that check
 * would be a second vocabulary deciding who may decide — the failure mode this phase keeps refusing.
 *
 * Three things did NOT change, and a reader should be able to check each in one line: the consumer is
 * itself dormant (`a6-pr2-lane-hygiene.test.ts` walks `packages/**` and requires ITS consumer set to be
 * empty, so nothing reaches it from production either); the consumer imports nothing from PR0 beyond the
 * three names above (`a6-pr2-lane-hygiene.test.ts` pins its whole import set against a closed
 * allow-list); and no Alpha.5 permission/refusal/EffectSet/Grant semantics moved — this PR0 spec is the
 * only file of #501's delivery that #507 touches, and it touches one constant here.
 */
const ALLOWED_CONSUMERS: readonly string[] = ['runtime/review-assignment/router.ts']

/** Prefixes inside the ARC-A protected center (the set
 *  `packages/testkit/test/arc-a-fitness/scan.mjs` pins; restated here as the
 *  dependency-direction question only — this test does not re-derive the
 *  digest ledger, u6-arc-a-fitness does). */
const PROTECTED_PREFIXES = [
  `control${sep}`,
  `operation-permission${sep}`,
  `tool-admission${sep}`,
  `tool-dispatch${sep}`,
  join('src', 'plugin', 'live', 'pa-mount-registry.mjs'),
  join('src', 'plugin', 'live', 'agent-bindings.mjs'),
  `governance-center${sep}`,
]

/**
 * Every file that could carry an import of the lane.
 *
 * The FIRST version of this walk looked only at `.ts`, and the review executed
 * the hole: the live plugin plane — `src/plugin/live/*.mjs`, the very place
 * PR-I2 will stand — is `.mjs`, so a `.mjs` file importing the lane left this
 * law GREEN. Build output is skipped (`dist`, `composition-shim`) because it is
 * derived: a lane that reaches production shows up in its sources first, and
 * pinning generated bytes would only make the failure arrive late and loud in
 * the wrong file.
 */
// `.tsx` is here because the round-5 review planted an importer in `alpha/src/offender.tsx` and the
// dormancy leg stayed GREEN while twelve production `packages/client/src/ui/*.tsx` files sat outside the
// walk — and PR-I2's wake states are exactly the kind of file that lands there. `.mts` needs nothing:
// every `.mts` in this tree is a `.d.mts` declaration, already excluded.
const SOURCE_EXTENSIONS = ['.ts', '.tsx', '.mjs', '.cjs', '.js']
const SKIPPED_DIRECTORIES = new Set(['node_modules', 'dist', 'composition-shim', 'coverage'])

/**
 * Did this error mean "the path is gone / its parent is gone", as opposed to "the filesystem is broken"?
 * Three sibling suites (f3a/f3b/f3c) and the po-notify suite create and destroy scratch under
 * `packages/testkit/test/.tmp-fault`, which every tree walk in this file crosses. A full-repo run measured
 * the collision rather than predicting it: the first version of this walker aborted the whole spec with
 * `ENOENT: no such file or directory, stat '.../.tmp-fault/po-notify-determinism'` — a spec whose claim is
 * about who imports a dormant lane, defeated because another suite happened to be mid-cleanup. Treating
 * "gone" as "gone" is not a weakened assertion: a file that no longer exists cannot import anything, and
 * anything OTHER than gone still throws, because a real filesystem problem must not look like success.
 */
const VANISHED = { count: 0 }

function isGoneError(error: unknown): boolean {
  const code = (error as NodeJS.ErrnoException | null)?.code
  return code === 'ENOENT' || code === 'ENOTDIR' || code === 'ELOOP'
}

function sourceFiles(root: string): string[] {
  const out: string[] = []
  let entries: string[]
  try {
    entries = readdirSync(root)
  } catch (error) {
    if (isGoneError(error)) {
      VANISHED.count += 1
      return out
    }
    throw error
  }
  for (const entry of entries) {
    const full = join(root, entry)
    let isDirectory = false
    try {
      isDirectory = statSync(full).isDirectory()
    } catch (error) {
      if (isGoneError(error)) {
        VANISHED.count += 1
        continue
      }
      throw error
    }
    if (isDirectory) {
      if (SKIPPED_DIRECTORIES.has(entry)) continue
      out.push(...sourceFiles(full))
      continue
    }
    if (entry.endsWith('.d.ts')) continue
    if (SOURCE_EXTENSIONS.some((extension) => entry.endsWith(extension))) out.push(full)
  }
  return out
}

/** Read a file that a concurrent suite may delete between listing and open. `null` means "it is gone",
 * which the dormancy scan reads as "nothing here imports the lane" — the truth for a deleted file. Used
 * ONLY for foreign trees; the lane's own files are read strictly, because a missing founding module must
 * fail loudly rather than vanish into an empty string. */
function readIfPresent(file: string): string | null {
  try {
    return readFileSync(file, 'utf8')
  } catch (error) {
    if (isGoneError(error)) {
      VANISHED.count += 1
      return null
    }
    throw error
  }
}

/**
 * Any mention of a lane module in a quoted specifier, with or without an
 * extension (the first version required `.js`, so an extensionless importer
 * slipped through), including a bare directory import and a dynamic
 * `import('…/review-mandate/plan.js')`, which no static-import scan sees.
 */
const LANE_IMPORT_PATTERN = /['"][^'"]*review-mandate\/(?:index|types|plan|mandate)(?:\.js)?['"]|['"][^'"]*\/review-mandate\/?['"]|import\(\s*['"][^'"]*review-mandate/

describe('a6-pr0 lane hygiene', () => {
  it('the lane exists and is more than a barrel', () => {
    const files = sourceFiles(LANE_DIR).map((file) => relative(LANE_DIR, file)).sort()
    // The LAW is that the lane is a real module set, not a re-export file: a
    // barrel-only lane would be a vocabulary dump with no enforcement inside it.
    for (const required of ['index.ts', 'mandate.ts', 'plan.ts', 'types.ts']) {
      expect(files, `the lane is missing ${required}`).toContain(required)
    }
    // Anything BEYOND the four founding modules must be named here, so a new
    // module in this lane is a deliberate amendment in its own PR rather than a
    // silent surprise — and so that adding a legitimate fifth module (PR-I1's
    // grant folding is the foreseeable one) is a one-line edit that says what
    // landed, instead of an unrelated hygiene leg going red.
    const EXTRA_MODULES_ALLOWED: readonly string[] = []
    expect(files.filter((file) => !['index.ts', 'mandate.ts', 'plan.ts', 'types.ts'].includes(file))).toEqual([...EXTRA_MODULES_ALLOWED])
  })

  it('is DORMANT: no production file outside the lane imports it yet', () => {
    const offenders: string[] = []
    // EVERY package, not a chosen six: contracts, legacy and testkit were
    // outside the first version's list, and a vocabulary import from the
    // contracts package is the most likely accidental consumer of all.
    const packages = readdirSync(PACKAGES_ROOT, { withFileTypes: true })
      .filter((entry) => entry.isDirectory())
      .map((entry) => entry.name)
      .sort()
    expect(packages.length).toBeGreaterThan(0)
    for (const pkg of packages) {
      const files = sourceFiles(join(PACKAGES_ROOT, pkg))
      // The floor that makes the whole leg non-vacuous. Before the round-5 review, a walk that read
      // ZERO files passed: the only anti-vacuity was counting package NAMES from a strict readdir of
      // PACKAGES_ROOT, so a renamed package, a wrong PACKAGES_ROOT, a subtree swallowed by a symlink
      // loop, or an extension filter too narrow to see anything all produced a green "no offenders".
      // Measured floor on this tree: the smallest package holds 20 source files (testkit 342, runtime
      // 827), so this cannot accidentally trip — and it is the assertion that would catch the next
      // vanishing-scratch race turning into silence instead of a skip.
      expect(files, `the dormancy walk found no source file inside ${pkg}`).not.toHaveLength(0)
      for (const file of files) {
        const rel = relative(PACKAGES_ROOT, file)
        if (rel.startsWith(join('runtime', 'review-mandate') + sep)) continue
        if (rel.includes(`${sep}test${sep}`) || rel.includes(`${sep}tests${sep}`) || rel.includes('.spec.')) continue
        if (LANE_IMPORT_PATTERN.test(readIfPresent(file) ?? '')) offenders.push(rel)
      }
    }
    expect(offenders).toEqual([...ALLOWED_CONSUMERS])
  })

  it.each<[string, string]>([
    ['a plain TypeScript importer', `import { evaluateReviewAdmission } from '../review-mandate/index.js'`],
    ['an extensionless TypeScript importer', `import { evaluateReviewAdmission } from '../review-mandate/index'`],
    ['a bare directory import', `import * as lane from '../review-mandate'`],
    ['a live-plane .mjs importer', `import { delegationApplicable } from '../review-mandate/index.js'`],
    ['a sibling-module import', `import { parseReviewPlan } from './review-mandate/plan.js'`],
    ['a dynamic import', `const lane = await import('../review-mandate/mandate.js')`],
  ])('the dormancy detector catches %s (positive control)', (_label, sample) => {
    // Without this leg the detector could be vacuous and the law above would
    // pass for the wrong reason — the exact failure the first review found.
    expect(LANE_IMPORT_PATTERN.test(sample)).toBe(true)
  })

  it('the dormancy detector does not fire on unrelated text (negative control)', () => {
    expect(LANE_IMPORT_PATTERN.test("import { parsePlan } from '../plan/index.js'")).toBe(false)
    expect(LANE_IMPORT_PATTERN.test('// review-mandate is dormant')).toBe(false)
  })

  it('imports NOTHING from the ARC-A protected center (no reverse dependency)', () => {
    for (const file of sourceFiles(LANE_DIR)) {
      const text = readFileSync(file, 'utf8')
      for (const prefix of PROTECTED_PREFIXES) {
        expect(text, `${relative(RUNTIME_ROOT, file)} must not import the protected ${prefix}`).not.toContain(`../${prefix}`)
        expect(text, `${relative(RUNTIME_ROOT, file)} must not import the protected ${prefix}`).not.toContain(`./${prefix}`)
      }
    }
  })

  it('is named by both tsconfigs, so a repo-wide tsc reads it', () => {
    expect(readFileSync(join(RUNTIME_ROOT, 'tsconfig.json'), 'utf8')).toContain('"review-mandate"')
    expect(readFileSync(join(RUNTIME_ROOT, 'tsconfig.build.json'), 'utf8')).toContain('"review-mandate"')
  })

  it('performs no I/O and reads no clock: only node:crypto, contracts and itself', () => {
    const allowed = /^(node:crypto|(?:\.\.\/)+contracts\/src\/index\.js|\.\/(types|plan|mandate)\.js)$/
    for (const file of sourceFiles(LANE_DIR)) {
      const text = readFileSync(file, 'utf8')
      const specifiers = [...text.matchAll(/^\s*(?:import|export)[^;]*?from '([^']+)'/gm)].map((match) => match[1] as string)
      for (const specifier of specifiers) {
        expect(allowed.test(specifier), `${relative(RUNTIME_ROOT, file)} imports ${specifier}, outside the pure-lane allow-list`).toBe(true)
      }
      // LEXICAL SCREEN, not the law itself. The law is that this lane's answer
      // depends only on its arguments, which is what the injected-clock legs in
      // a6-pr0-mandate-admission prove; this screen exists so a future edit
      // that reads the wall clock, spawns a timer, or reaches for a module
      // outside the allow-list fails here instead of in a reviewer's reading.
      // It is a floor and can be argued with; it is not the proof.
      expect(text).not.toMatch(/Date\.now\(/)
      expect(text).not.toMatch(/new Date\(\s*\)/)
      expect(text).not.toMatch(/performance\.now|process\.hrtime/)
      expect(text).not.toMatch(/setTimeout|setInterval|setImmediate/)
      expect(text).not.toMatch(/\brequire\s*\(/)
      expect(text).not.toMatch(/\bimport\s*\(/)
      expect(text).not.toMatch(/readFileSync|writeFileSync|process\.env|fetch\(|node:fs|node:net|node:http|child_process/)
    }
  })
})

describe('the tree walk survives a concurrent suite\'s scratch cleanup', () => {
  it('skips an entry that vanished, counts it, and still sees what exists', () => {
    // Deterministic model of the race: a symlink whose target does not exist makes `statSync` throw
    // ENOENT on every OS, which is exactly what a sibling suite mid-`rm -rf` produces on one entry.
    // The leg is not only "did not throw" — it pins that the resilient walk still SEES the real file
    // and still matches the lane pattern in it, so resilience cannot quietly become blindness.
    const dir = mkdtempSync(join(tmpdir(), 'a6-hygiene-walk-'))
    try {
      mkdirSync(join(dir, 'pkg', 'src'), { recursive: true })
      const keeper = join(dir, 'pkg', 'src', 'keeper.ts')
      writeFileSync(keeper, "import { evaluateReviewAdmission } from '../review-mandate/index.js'\n")
      symlinkSync(join(dir, 'already-deleted'), join(dir, 'pkg', 'src', 'dangling.ts'))
      const before = VANISHED.count
      const files = sourceFiles(join(dir, 'pkg'))
      expect(files).toContain(keeper)
      expect(files).not.toContain(join(dir, 'pkg', 'src', 'dangling.ts'))
      expect(VANISHED.count, 'the vanished entry must be counted, not swallowed').toBeGreaterThan(before)
      expect(LANE_IMPORT_PATTERN.test(readFileSync(keeper, 'utf8'))).toBe(true)
      // And a read that races the same way yields null, not a throw, for a foreign tree.
      // The sibling suite's cleanup is `rm -rf .tmp-fault`, which throws from the DIRECTORY listing,
      // not from the per-entry stat the dangling symlink models. Both catches must be owned.
      expect(sourceFiles(join(dir, 'already-deleted')), 'a directory that vanished mid-walk yields no files and no throw').toEqual([])
      expect(readIfPresent(keeper), 'a file that is still there must still be readable through the tolerant path').not.toBeNull()
    } finally {
      rmSync(dir, { recursive: true, force: true })
    }
  })
})
