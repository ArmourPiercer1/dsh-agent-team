#!/usr/bin/env bash
# install-trial-profile.sh — write the TRIAL profile layer (governed Member realm)
# and the Leader+Worker+Officer blueprint into an isolated DSH_HOME.
#
# Usage:
#   export DSH_HOME=/absolute/path/to/trial-home        # NOT ~/.dsh
#   bash docs/trial/install-trial-profile.sh
#
# Optional:
#   TRIAL_PROVIDER / TRIAL_MODEL   (default: deepseek-official / deepseek-v4-flash)
#   TRIAL_WORKSPACE                (default: $DSH_HOME/trial-workspace)
#
# It refuses to write into the stable instance home, and it never edits the
# installed bundle copy: everything it writes lives under $DSH_HOME.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
DOC="$HERE/trial-team.v4.yaml"

if [[ -z "${DSH_HOME:-}" ]]; then
  echo "refused: export DSH_HOME=<isolated trial home> first (never ~/.dsh)" >&2
  exit 2
fi
DSH_HOME="$(cd "$DSH_HOME" && pwd)"
case "$DSH_HOME" in
  "$HOME/.dsh"|"$HOME/.dsh/"*) echo "refused: $DSH_HOME is the stable instance home" >&2; exit 2;;
esac
PROFILE="$DSH_HOME/profiles/web"
[[ -f "$PROFILE/package.json" ]] || { echo "refused: no installed web profile at $PROFILE (run the plugin add first)" >&2; exit 2; }
[[ -f "$DOC" ]] || { echo "refused: blueprint template missing: $DOC" >&2; exit 2; }

WORKSPACE="${TRIAL_WORKSPACE:-$DSH_HOME/trial-workspace}"
PROVIDER="${TRIAL_PROVIDER:-deepseek-official}"
MODEL="${TRIAL_MODEL:-deepseek-v4-flash}"

mkdir -p "$WORKSPACE" "$DSH_HOME/blueprints" "$DSH_HOME/centre" "$DSH_HOME/a5sf-evidence"
sed "s|@WORKSPACE@|$WORKSPACE|g" "$DOC" > "$DSH_HOME/blueprints/trial-team.yaml"

# The profile layer REPLACES the bundle's `dsh-agent-team` row config WHOLE
# (last-write-wins, no field merge), so the row below restates every required
# key and adds the governed-realm keys.
{
  cat <<YAML
# Generated by docs/trial/install-trial-profile.sh — regenerate, do not hand-edit.
# Layer order: this profile layer is applied AFTER the installed bundle.
- id: dsh-agent-team
  config:
    bootPhase: create-or-open
    rootSessionId: team-root
    blueprintSource: |
YAML
  sed 's/^/      /' "$DSH_HOME/blueprints/trial-team.yaml"
  cat <<YAML
    blueprintDir: "$DSH_HOME/blueprints"
    seedMembers: []
    generation: 1
    deniedSelection: null
    mcpServers: []
    staticModel:
      provider: "$PROVIDER"
      model: "$MODEL"
    environmentFacts:
      - { domain: "tool", subject: "web", available: true, generation: 1 }
      - { domain: "skill", subject: "base", available: true, generation: 1 }
      - { domain: "persona", subject: "standard", available: true, generation: 1 }
    externalPolicyFacts:
      hard: {}
      capabilityExists: {}
    defaultWorkspace: "$WORKSPACE"
    memberPresetId: a5sf-governed-member
    a5sfGovernedRealm: true
    centreStatePath: "$DSH_HOME/centre"
    a5sfEvidencePath: "$DSH_HOME/a5sf-evidence/consult.jsonl"
YAML
} > "$PROFILE/cordis.patch.yml"

echo "TRIAL-PROFILE-WRITTEN"
echo "  dsh_home        = $DSH_HOME"
echo "  profile_layer   = $PROFILE/cordis.patch.yml"
echo "  blueprint       = $DSH_HOME/blueprints/trial-team.yaml"
echo "  workspace       = $WORKSPACE"
echo "  centre_state    = $DSH_HOME/centre"
echo "  model           = $PROVIDER / $MODEL"
echo "next: start the host on a non-3080 port, e.g."
echo "  pnpm dsh web --port 3180 --host 127.0.0.1 --no-open"
